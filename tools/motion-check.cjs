const {chromium}=require(process.argv[2]||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const base=process.argv[3]||'http://127.0.0.1:4173/';
 const page=await browser.newPage({viewport:{width:1366,height:768},reducedMotion:'no-preference'});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'gry-na-zamowienie.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('.subpage-intro').classList.contains('motion-arrived'));
 assert.ok(await page.locator('.subpage-intro').evaluate(e=>e.getAnimations().length>0),'Hero entrance runs');
 const first=page.locator('.steps > li').nth(3);
 await first.evaluate(e=>e.scrollIntoView({block:'center'}));
 await page.waitForFunction(()=>document.querySelectorAll('.steps > li')[3].classList.contains('motion-arrived'));
 const initial=await first.evaluate(e=>({top:e.offsetTop,height:e.offsetHeight,animations:e.getAnimations().length}));
 assert.ok(initial.animations>0,'Process reveal runs on scroll');
 await first.evaluate(e=>Promise.all(e.getAnimations().map(a=>a.finished.catch(()=>{}))));
 const final=await first.evaluate(e=>({top:e.offsetTop,height:e.offsetHeight,opacity:getComputedStyle(e).opacity}));
 assert.equal(final.top,initial.top,'Motion does not change layout positions');
 assert.equal(final.height,initial.height,'Motion does not change section heights');
 assert.equal(final.opacity,'1','Content remains fully visible after animation');
 await page.goto(base+'firmy.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('.subpage-intro').classList.contains('motion-arrived'));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.getAnimations().length===0,{},{timeout:1000});
 assert.equal(await page.evaluate(()=>document.getAnimations().length),0,'Changing motion preference cancels animations');
 await page.reload();
 assert.equal(await page.locator('.motion-arrived').count(),0,'Reduced motion does not start reveals');
 await page.locator('.search-toggle').click();
 assert.equal(await page.locator('dialog[open]').evaluate(e=>getComputedStyle(e).animationName),'none','Dialog respects reduced motion');
 await page.keyboard.press('Escape');
 const unsupported=await browser.newContext();
 await unsupported.addInitScript(()=>window.IntersectionObserver=undefined);
 const fallback=await unsupported.newPage();
 await fallback.goto(base+'szkoly.html');
 assert.equal(await fallback.locator('.motion-arrived').count(),0);
 assert.equal(await fallback.locator('.subpage-intro').evaluate(e=>getComputedStyle(e).opacity),'1');
 const plain=await browser.newContext({javaScriptEnabled:false});
 const html=await plain.newPage();
 for(const route of ['szkoly','firmy','gry-na-zamowienie','misja','kontakt']) {
  await html.goto(base+route+'.html');
  assert.equal(await html.locator('main h1').count(),1);
  assert.equal(await html.locator('.subpage-intro').evaluate(e=>getComputedStyle(e).opacity),'1');
  assert.ok(await html.locator('main').innerText().then(text=>text.length>150));
  assert.equal(await html.locator('meta[name="robots"][content*="noindex"]').count(),0);
 }
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('MOTION PASS: entrance and scroll animations, stable layout, reduced motion including live preference changes, observer fallback, and visible static content without JavaScript.');
})().catch(e=>{console.error(e);process.exit(1)});
